import assert from 'node:assert/strict';
import {mkdtempSync, writeFileSync, mkdirSync, symlinkSync, readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {resolve, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync, spawnSync} from 'node:child_process';
import {byteRange, startServer} from './serve.mjs';
import {fresh, probe, rate} from './media.mjs';

const scripts = dirname(fileURLToPath(import.meta.url));
const directory = mkdtempSync(resolve(tmpdir(), 'video-director-tests-'));
const root = resolve(directory, 'site'); mkdirSync(root);
writeFileSync(resolve(root, 'index.html'), '0123456789');
writeFileSync(resolve(directory, 'outside.txt'), 'outside');
writeFileSync(resolve(root, '.env'), 'not-a-real-secret');
symlinkSync(resolve(directory, 'outside.txt'), resolve(root, 'escape.txt'));
symlinkSync(resolve(root, '.env'), resolve(root, 'alias.txt'));
symlinkSync(resolve(root, 'index.html'), resolve(root, 'valid-alias.html'));
assert.deepEqual(byteRange('bytes=3-5', 10), {start: 3, end: 5});
assert.deepEqual(byteRange('bytes=-3', 10), {start: 7, end: 9});
assert.deepEqual(byteRange('bytes=5-', 10), {start: 5, end: 9});
for (const value of ['bytes=-0', 'bytes=20-', 'bytes=7-2', 'bytes=0-1,4-5', 'bytes=-', 'oops']) assert.equal(byteRange(value, 10), null);
const local = await startServer(root);
try {
  const full = await fetch(local.origin); assert.equal(await full.text(), '0123456789');
  const range = await fetch(local.origin, {headers: {Range: 'bytes=2-4'}});
  assert.equal(range.status, 206); assert.equal(range.headers.get('content-range'), 'bytes 2-4/10'); assert.equal(await range.text(), '234');
  assert.equal((await fetch(local.origin, {headers: {Range: 'bytes=20-'}})).status, 416);
  assert.equal((await fetch(local.origin, {method: 'HEAD'})).headers.get('content-length'), '10');
  assert.equal((await fetch(local.origin, {method: 'POST'})).status, 405);
  assert.equal((await fetch(local.origin + '/.env')).status, 403);
  assert.equal((await fetch(local.origin + '/escape.txt')).status, 403);
  assert.equal((await fetch(local.origin + '/alias.txt')).status, 403);
  assert.equal(await (await fetch(local.origin + '/valid-alias.html')).text(), '0123456789');
  assert.equal((await fetch(local.origin + '/..%2foutside.txt')).status, 403);
} finally {await local.close();}
assert.throws(() => fresh(resolve(root, 'index.html')), /Preserving/);
assert.equal(rate('60000/1001'), 60000 / 1001);
const tone = resolve(directory, 'tone.wav');
execFileSync('ffmpeg', ['-n', '-v', 'error', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=0.1', tone]);
const manifest = resolve(directory, 'audio.json'), output = resolve(directory, 'assembled.wav');
writeFileSync(manifest, JSON.stringify({clips: [{file: tone, gapAfter: 0.25}, {file: tone, gapAfter: 0.1}]}));
execFileSync(process.execPath, [resolve(scripts, 'audio.mjs'), manifest, output]);
assert.ok(Math.abs(Number(probe(output).format.duration) - 0.55) < 0.001);
const timing = JSON.parse(readFileSync(output + '.timing.json'));
assert.ok(Math.abs(timing.clips[1].start - 0.35) < 0.001);
assert.notEqual(spawnSync(process.execPath, [resolve(scripts, 'audio.mjs'), manifest, output]).status, 0);
writeFileSync(manifest, JSON.stringify({clips: [{file: tone, gapAfter: -1}]}));
assert.notEqual(spawnSync(process.execPath, [resolve(scripts, 'audio.mjs'), manifest, resolve(directory, 'invalid.wav')]).status, 0);
assert.notEqual(spawnSync(process.execPath, [resolve(scripts, 'capture.mjs'), '--seconds', '0', '--out', resolve(directory, 'invalid.mp4')]).status, 0);
console.log(JSON.stringify({passed: true, groups: ['ranges', 'HTTP', 'path containment', 'overwrite', 'audio timing', 'invalid pause', 'invalid duration'], fixtures: directory}));
